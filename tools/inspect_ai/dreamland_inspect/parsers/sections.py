"""Split compound command output into labeled sections."""

from __future__ import annotations

import re
from dataclasses import dataclass

SECTION_RE = re.compile(r"^\s*==\s*(?P<title>[^=\n].*?)\s*==\s*$")


@dataclass(frozen=True, slots=True)
class OutputSection:
    title: str
    body: str


def split_sections(stdout: str) -> list[OutputSection]:
    """Split output on lines like `== identity ==`.

    Compound probes generated by agents commonly use printf markers. Keeping
    these sections lets scorers reason about one command event without losing
    the subcommand intent.
    """

    sections: list[OutputSection] = []
    current_title = "output"
    current_lines: list[str] = []
    saw_marker = False

    for line in stdout.splitlines():
        match = SECTION_RE.match(line)
        if match:
            if current_lines or saw_marker:
                sections.append(
                    OutputSection(
                        title=current_title,
                        body="\n".join(current_lines).strip("\n"),
                    )
                )
            current_title = _normalize_title(match.group("title"))
            current_lines = []
            saw_marker = True
        else:
            current_lines.append(line)

    if current_lines or not sections:
        sections.append(
            OutputSection(
                title=current_title,
                body="\n".join(current_lines).strip("\n"),
            )
        )
    return [
        section
        for section in sections
        if section.title != "output" or section.body or len(sections) == 1
    ]


def section_map(stdout: str) -> dict[str, str]:
    result: dict[str, str] = {}
    for section in split_sections(stdout):
        result[section.title] = section.body
    return result


def _normalize_title(title: str) -> str:
    return re.sub(r"\s+", " ", title.strip().lower())

